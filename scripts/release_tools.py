"""Shared release checks. Standard library only; no credentials are printed."""
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = "com.ubers.observador"


def run(args, **kwargs):
    return subprocess.check_output([str(arg) for arg in args], cwd=ROOT,
                                   stderr=subprocess.STDOUT, **kwargs).decode("utf-8", errors="replace").strip()


def sdk_path():
    for key in ("ANDROID_HOME", "ANDROID_SDK_ROOT"):
        if os.environ.get(key):
            return Path(os.environ[key])
    if os.environ.get("LOCALAPPDATA"):
        return Path(os.environ["LOCALAPPDATA"]) / "Android/Sdk"
    raise RuntimeError("Define ANDROID_HOME con la ruta al SDK")


def sdk_tool(name):
    suffix = ".exe" if os.name == "nt" else ""
    if name == "adb":
        return sdk_path() / "platform-tools" / (name + suffix)
    versions = sorted((p for p in (sdk_path() / "build-tools").iterdir()
                       if re.fullmatch(r"\d+(?:\.\d+)+", p.name)),
                      key=lambda p: tuple(map(int, p.name.split("."))), reverse=True)
    for version in versions:
        candidate = version / ("lib/apksigner.jar" if name == "apksigner" else name + suffix)
        if candidate.is_file():
            return candidate
    raise RuntimeError("Herramienta SDK no encontrada: " + name)


def app_identity(source):
    name = re.search(r'versionName\s*=\s*"([^"]+)"', source)
    code = re.search(r"versionCode\s*=\s*(\d+)", source)
    if not name or not code:
        raise ValueError("Falta versionName o versionCode")
    return name[1], int(code[1])


def canonical_schema(content):
    # Normalize formatting/key order, while preserving JSON value types and array order.
    return json.dumps(json.loads(content), sort_keys=True, separators=(",", ":"), ensure_ascii=False)


def source_checks():
    version, code = app_identity((ROOT / "app/build.gradle.kts").read_text(encoding="utf-8"))
    catalog = json.loads((ROOT / "docs/releases/versiones.json").read_text(encoding="utf-8"))
    if len({e["version"] for e in catalog}) != len(catalog) or len({e["versionCode"] for e in catalog}) != len(catalog):
        raise ValueError("Catálogo duplicado")
    if catalog[-1]["version"] != version or catalog[-1]["versionCode"] != code:
        raise ValueError("La versión actual debe cerrar el catálogo")
    declared = re.findall(r"^## \[(\d+\.\d+\.\d+)\]", (ROOT / "CHANGELOG.md").read_text(encoding="utf-8-sig"), re.M)
    if len(declared) != len(catalog) or set(declared) != {e["version"] for e in catalog}:
        raise ValueError("Catálogo y changelog no coinciden")
    card = (ROOT / f"docs/releases/changelogs/{version}.md").read_text(encoding="utf-8")
    section = re.search(r"^## Novedades en la app\s*\n(.*?)(?=^## |\Z)", card, re.M | re.S)
    if not section or not re.search(r"^- \S", section[1], re.M):
        raise ValueError("Faltan novedades para el conductor")
    for entry in catalog:
        if entry["tag"] != "v" + entry["version"] or entry["branch"] != "release/" + entry["version"]:
            raise ValueError("Referencias inesperadas en el catálogo")
        if not (ROOT / f"docs/releases/changelogs/{entry['version']}.md").is_file():
            raise ValueError("Falta ficha histórica")
    previous = catalog[-2]
    old_source = run(["git", "show", previous["tag"] + ":app/build.gradle.kts"])
    if app_identity(old_source) != (previous["version"], previous["versionCode"]):
        raise ValueError("La base no corresponde a la entrega anterior")
    if code != previous["versionCode"] + 1:
        raise ValueError("versionCode debe aumentar exactamente en uno")
    db_source = (ROOT / "app/src/main/java/com/ubers/observador/data/db/AppDatabase.kt").read_text(encoding="utf-8")
    db_version = int(re.search(r"\bversion\s*=\s*(\d+)", db_source)[1])
    directory = "app/schemas/com.ubers.observador.data.db.AppDatabase"
    schema = json.loads((ROOT / directory / f"{db_version}.json").read_text(encoding="utf-8"))
    if schema["database"]["version"] != db_version:
        raise ValueError("Esquema Room incompatible")
    # Compare JSON, not checkout line endings (Windows may use CRLF).
    for path in run(["git", "ls-tree", "-r", "--name-only", previous["tag"], directory]).splitlines():
        old = subprocess.check_output(["git", "show", previous["tag"] + ":" + path], cwd=ROOT)
        if not (ROOT / path).is_file() or canonical_schema((ROOT / path).read_text(encoding="utf-8")) != canonical_schema(old):
            raise ValueError("Se modificó un esquema histórico: " + path)
    return {"versionName": version, "versionCode": code, "databaseVersion": db_version,
            "schemaIdentity": schema["database"]["identityHash"], "previousTag": previous["tag"]}


def parse_badging(output):
    # Instrumentation APKs generated by AGP may legitimately have empty version fields.
    match = re.search(r"^package: name='([^']+)' versionCode='(\d*)' versionName='([^']*)'", output, re.M)
    if not match:
        raise ValueError("No se pudo leer la identidad del APK")
    return {"package": match[1], "versionCode": int(match[2] or 0), "versionName": match[3],
            "debuggable": bool(re.search(r"^application-debuggable", output, re.M))}


def certificate_hashes(output):
    hashes = re.findall(r"^Signer #\d+ certificate SHA-256 digest: ([0-9a-fA-F]{64})\s*$", output, re.M)
    if not hashes:
        raise ValueError("El APK no tiene certificados verificables")
    return sorted(set(value.lower() for value in hashes))


def inspect_apk(path):
    path = Path(path).resolve(strict=True)
    identity = parse_badging(run([sdk_tool("aapt"), "dump", "badging", path]))
    java = Path(os.environ["JAVA_HOME"]) / "bin" / ("java.exe" if os.name == "nt" else "java") if os.environ.get("JAVA_HOME") else "java"
    certs = certificate_hashes(run([java, "-jar", sdk_tool("apksigner"), "verify", "--print-certs", path]))
    return dict(identity, sha256=hashlib.sha256(path.read_bytes()).hexdigest(),
                sizeBytes=path.stat().st_size, certificatesSha256=certs)


def check_update(previous, current):
    if previous["package"] != current["package"]:
        raise ValueError("No es el mismo paquete")
    if current["versionCode"] <= previous["versionCode"]:
        raise ValueError("La actualización no aumenta versionCode")
    if previous["certificatesSha256"] != current["certificatesSha256"]:
        raise ValueError("Firma distinta: actualización directa rechazada; no desinstalar")


def instrumentation_count(output):
    match = re.search(r"^OK \((\d+) tests?\)\s*$", output, re.M)
    if not match or int(match[1]) == 0 or re.search(
            r"FAILURES!!!|INSTRUMENTATION_FAILED|shortMsg=|Process crashed|INSTRUMENTATION_STATUS_CODE: -[1-4]\b", output):
        raise ValueError("La instrumentación no terminó con pruebas correctas")
    return int(match[1])
